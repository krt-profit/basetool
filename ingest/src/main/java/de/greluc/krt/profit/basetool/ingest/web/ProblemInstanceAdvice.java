package de.greluc.krt.profit.basetool.ingest.web;

import java.net.URI;
import org.jetbrains.annotations.Nullable;
import org.springframework.core.MethodParameter;
import org.springframework.http.MediaType;
import org.springframework.http.ProblemDetail;
import org.springframework.http.converter.HttpMessageConverter;
import org.springframework.http.server.ServerHttpRequest;
import org.springframework.http.server.ServerHttpResponse;
import org.springframework.http.server.ServletServerHttpRequest;
import org.springframework.web.bind.annotation.RestControllerAdvice;
import org.springframework.web.servlet.mvc.method.annotation.ResponseBodyAdvice;

/**
 * Sets the {@code instance} of a problem a route or an exception handler answers to the request
 * path when it carries none, the member the exchange contract records on those answers
 * (REQ-XCH-036); Spring MVC leaves it empty.
 *
 * <p>Problems written by a servlet filter never pass through Spring MVC and keep no {@code
 * instance}, as the contract states.
 */
@RestControllerAdvice
public class ProblemInstanceAdvice implements ResponseBodyAdvice<Object> {

  @Override
  public boolean supports(
      MethodParameter returnType, Class<? extends HttpMessageConverter<?>> converterType) {
    return true;
  }

  @Override
  public @Nullable Object beforeBodyWrite(
      @Nullable Object body,
      MethodParameter returnType,
      MediaType selectedContentType,
      Class<? extends HttpMessageConverter<?>> selectedConverterType,
      ServerHttpRequest request,
      ServerHttpResponse response) {
    if (body instanceof ProblemDetail problem
        && problem.getInstance() == null
        && request instanceof ServletServerHttpRequest servletRequest) {
      problem.setInstance(URI.create(servletRequest.getServletRequest().getRequestURI()));
    }
    return body;
  }
}
