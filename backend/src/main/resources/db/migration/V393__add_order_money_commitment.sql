CREATE TABLE job_order_money_commitment (
    id UUID PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES job_order (id) ON DELETE CASCADE,
    unit_id UUID NOT NULL REFERENCES org_unit (id),
    participation_id UUID REFERENCES job_order_participation (id) ON DELETE SET NULL,
    outstanding NUMERIC NOT NULL CHECK (outstanding >= 0 AND outstanding < 'Infinity'::numeric AND outstanding = trunc(outstanding)),
    opened_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL,
    UNIQUE (order_id, id),
    CHECK ((ended_at IS NULL AND outstanding > 0) OR (ended_at IS NOT NULL AND outstanding = 0))
);

CREATE UNIQUE INDEX uq_job_order_money_commitment_current
    ON job_order_money_commitment (order_id, unit_id) WHERE ended_at IS NULL;

CREATE INDEX idx_job_order_money_commitment_order ON job_order_money_commitment (order_id);
CREATE INDEX idx_job_order_money_commitment_unit ON job_order_money_commitment (unit_id);
CREATE INDEX idx_job_order_money_commitment_participation ON job_order_money_commitment (participation_id);

ALTER TABLE job_order_money_operation
    ADD COLUMN commitment_id UUID,
    ADD FOREIGN KEY (order_id, commitment_id) REFERENCES job_order_money_commitment (order_id, id);

CREATE INDEX idx_job_order_money_operation_commitment ON job_order_money_operation (order_id, commitment_id);

CREATE TABLE job_order_money_commitment_change (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL,
    commitment_id UUID NOT NULL,
    operation_id UUID,
    reason VARCHAR(32) NOT NULL,
    before_amount NUMERIC NOT NULL CHECK (before_amount >= 0 AND before_amount < 'Infinity'::numeric AND before_amount = trunc(before_amount)),
    after_amount NUMERIC NOT NULL CHECK (after_amount >= 0 AND after_amount < 'Infinity'::numeric AND after_amount = trunc(after_amount)),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY (order_id, commitment_id) REFERENCES job_order_money_commitment (order_id, id) ON DELETE CASCADE,
    FOREIGN KEY (order_id, operation_id) REFERENCES job_order_money_operation (order_id, operation_id),
    UNIQUE (order_id, operation_id)
);

CREATE INDEX idx_job_order_money_commitment_change_order ON job_order_money_commitment_change (order_id, id);
CREATE INDEX idx_job_order_money_commitment_change_commitment ON job_order_money_commitment_change (order_id, commitment_id);

