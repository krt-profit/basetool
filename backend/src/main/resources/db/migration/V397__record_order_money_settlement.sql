ALTER TABLE job_order_money_operation
    ADD COLUMN peer_order_id UUID,
    DROP CONSTRAINT job_order_money_operation_amount_check,
    DROP CONSTRAINT chk_job_order_money_operation_movement,
    ADD CONSTRAINT chk_job_order_money_operation_amount CHECK (
        amount < 'Infinity'::numeric AND amount = trunc(amount)
        AND ((kind = 'CORRECTION' AND amount = 0) OR (kind <> 'CORRECTION' AND amount > 0))
    ),
    ADD CONSTRAINT chk_job_order_money_operation_purpose CHECK (
        (kind IN ('PURPOSE_INFLOW', 'PURPOSE_OUTFLOW')
            AND peer_order_id IS NOT NULL AND peer_order_id <> order_id)
        OR (kind NOT IN ('PURPOSE_INFLOW', 'PURPOSE_OUTFLOW') AND peer_order_id IS NULL)
    ),
    ADD CONSTRAINT chk_job_order_money_operation_movement CHECK (
        (kind IN ('PROVISION', 'PURPOSE_INFLOW', 'PURPOSE_OUTFLOW', 'RELEASE', 'SHORTAGE', 'CORRECTION')
            AND destination_holder_id IS NULL AND recipient_id IS NULL
            AND new_provision IS NULL AND fee_rate IS NULL AND fee IS NULL)
        OR
        (new_provision IS NOT NULL AND new_provision >= 0 AND new_provision < 'Infinity'::numeric
            AND new_provision = trunc(new_provision)
            AND fee_rate IS NOT NULL AND fee_rate >= 0 AND fee_rate < 1
            AND fee IS NOT NULL AND fee >= 0 AND fee < 'Infinity'::numeric AND fee = trunc(fee)
            AND ((kind = 'COLLECTION' AND destination_holder_id IS NOT NULL AND recipient_id IS NULL)
                OR (kind = 'HANDOVER' AND destination_holder_id IS NULL AND recipient_id IS NOT NULL)
                OR (kind = 'REQUESTER_RETURN' AND destination_holder_id IS NOT NULL AND recipient_id IS NOT NULL)
                OR (kind = 'SETTLEMENT' AND destination_holder_id IS NULL AND recipient_id IS NULL)
                OR (kind = 'PURPOSE_HANDOVER' AND destination_holder_id IS NULL AND recipient_id IS NOT NULL
                    AND new_provision = 0 AND fee_rate = 0 AND fee = 0)))
    );

CREATE TABLE job_order_money_correction_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL,
    correction_operation_id UUID NOT NULL,
    original_operation_id UUID NOT NULL,
    previous_amount NUMERIC NOT NULL,
    previous_provision NUMERIC NOT NULL,
    previous_fee NUMERIC NOT NULL,
    amount NUMERIC NOT NULL,
    provision NUMERIC NOT NULL,
    fee NUMERIC NOT NULL,
    UNIQUE (order_id, correction_operation_id, original_operation_id),
    FOREIGN KEY (order_id, correction_operation_id)
        REFERENCES job_order_money_operation (order_id, operation_id) ON DELETE CASCADE,
    FOREIGN KEY (order_id, original_operation_id)
        REFERENCES job_order_money_operation (order_id, operation_id),
    CHECK (original_operation_id <> correction_operation_id),
    CHECK (previous_amount >= 0 AND previous_amount < 'Infinity'::numeric
        AND previous_amount = trunc(previous_amount)),
    CHECK (previous_provision >= 0 AND previous_provision < 'Infinity'::numeric
        AND previous_provision = trunc(previous_provision)),
    CHECK (previous_fee >= 0 AND previous_fee < 'Infinity'::numeric AND previous_fee = trunc(previous_fee)),
    CHECK (amount >= 0 AND amount < 'Infinity'::numeric AND amount = trunc(amount)),
    CHECK (provision >= 0 AND provision < 'Infinity'::numeric AND provision = trunc(provision)),
    CHECK (fee >= 0 AND fee < 'Infinity'::numeric AND fee = trunc(fee))
);

CREATE INDEX idx_job_order_money_correction_order ON job_order_money_correction_entry (order_id, id);
CREATE INDEX idx_job_order_money_correction_original ON job_order_money_correction_entry (order_id, original_operation_id);

CREATE TABLE job_order_money_holder_change (
    id UUID PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES job_order (id) ON DELETE CASCADE,
    holder_id UUID NOT NULL,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('NAME', 'LINK', 'MERGE', 'CORRECT_LINK')),
    actor_id UUID REFERENCES app_user (id) ON DELETE SET NULL,
    previous_user_id UUID REFERENCES app_user (id) ON DELETE SET NULL,
    user_id UUID REFERENCES app_user (id) ON DELETE SET NULL,
    previous_name VARCHAR(200),
    name VARCHAR(200),
    target_holder_id UUID,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY (order_id, holder_id) REFERENCES job_order_money_holder (order_id, id),
    FOREIGN KEY (order_id, target_holder_id) REFERENCES job_order_money_holder (order_id, id),
    CHECK ((kind = 'MERGE') = (target_holder_id IS NOT NULL)),
    CHECK (target_holder_id IS DISTINCT FROM holder_id),
    CHECK (num_nonnulls(previous_user_id, previous_name) <= 1),
    CHECK (num_nonnulls(user_id, name) <= 1)
);

CREATE INDEX idx_job_order_money_holder_change_history
    ON job_order_money_holder_change (order_id, recorded_at, id);
CREATE INDEX idx_job_order_money_holder_change_holder
