package de.greluc.krt.profit.basetool.backend.operation.internal;

import de.greluc.krt.profit.basetool.backend.platform.api.UserErasureParticipant;
import java.util.Map;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import org.jetbrains.annotations.NotNull;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

/**
 * Takes a departing member's id out of the operation payout marks for the account deletion: each
 * mark moves to the deleted-account key of the member's participation, so a settled operation keeps
 * its paid state without naming the account (REQ-DATA-008).
 */
@Component
@RequiredArgsConstructor
@Transactional(propagation = Propagation.MANDATORY)
public class OperationPayoutMemberUnlink implements UserErasureParticipant {

  /** Runs before the mission unlink, which clears the participant link this re-keying reads. */
  static final int POSITION = 5;

  private final OperationPayoutStatusRepository payoutStatusRepository;

  @Override
  public @NotNull Phase phase() {
    return Phase.UNLINK;
  }

  @Override
  public int position() {
    return POSITION;
  }

  /**
   * Re-keys every payout mark held under the member's id.
   *
   * @param userId the departing member's {@code app_user.id}
   * @param fallbackAdminId unused
   * @return no counts
   */
  @Override
  public @NotNull Map<Erased, Integer> erase(@NotNull UUID userId, @NotNull UUID fallbackAdminId) {
    payoutStatusRepository.rekeyDeletedMember(userId.toString());
    return Map.of();
  }
}
