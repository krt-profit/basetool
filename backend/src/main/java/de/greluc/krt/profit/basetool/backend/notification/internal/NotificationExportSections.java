package de.greluc.krt.profit.basetool.backend.notification.internal;

import static de.greluc.krt.profit.basetool.backend.platform.api.PersonalDataExportSection.LegalBasis.ART_15;
import static de.greluc.krt.profit.basetool.backend.platform.api.PersonalDataExportSection.LegalBasis.ART_15_20;

import de.greluc.krt.profit.basetool.backend.platform.api.PersonalDataExportSection;
import java.util.List;
import org.jetbrains.annotations.NotNull;
import org.springframework.stereotype.Component;

/**
 * The notification's part of the Art. 15 / Art. 20 data export: the member's notifications, mutes
 * and rule targets (REQ-SEC-058).
 */
@Component
public class NotificationExportSections implements PersonalDataExportSection {

  @Override
  public @NotNull List<Section> sections() {
    return List.of(
        new Section(
                200,
                "notifications",
                ART_15,
                "Generated by the system for the member. The render parameters can name whoever"
                    + " triggered the event and are therefore scrubbed.",
                """
                SELECT type, entity_type, params, is_read, read_at, created_at
                FROM notification WHERE recipient_user_id = :userId ORDER BY created_at
                """)
            .scrubbing("params"),
        new Section(
            210,
            "notificationMutes",
            ART_15_20,
            "Chosen by the member: the notification types they do not receive.",
            """
            SELECT notification_type, created_at
            FROM notification_mute WHERE user_id = :userId ORDER BY notification_type
            """),
        new Section(
                220,
                "notificationRuleTargets",
                ART_15,
                "Rules that name the member as a recipient; configured by an administrator.",
                """
                SELECT r.description AS rule, s.kind
                FROM notification_rule_selector s JOIN notification_rule r ON r.id = s.rule_id
                WHERE s.user_id = :userId ORDER BY r.description
                """)
            .scrubbing("rule"));
  }
}
