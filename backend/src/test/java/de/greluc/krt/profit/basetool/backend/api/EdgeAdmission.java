  /** A literal path segment: no character a regular expression would read as syntax but a dot. */
  private static final Pattern LITERAL_SEGMENT = Pattern.compile("[A-Za-z0-9_~.-]+");

  /** A placeholder path segment. */
  private static final Pattern PLACEHOLDER_SEGMENT = Pattern.compile("\\{([A-Za-z][A-Za-z0-9]*)}");

  /** One operation as written in the frozen set, the anonymous reads or the retired list. */
  private static final Pattern OPERATION = Pattern.compile("^([A-Z]+) (/api/\\S+)$");

  /** One admission entry of the committed map: group 1 the verb, group 2 the path expression. */
  private static final Pattern MAP_ENTRY =
      Pattern.compile("^  \"~\\^([A-Z]+):(/[^\"$^]+)\\$\" 1;$");

