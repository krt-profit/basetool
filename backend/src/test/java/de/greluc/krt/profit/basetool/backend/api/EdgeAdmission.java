/**
 * Renders the API vhost's admission from the frozen contract set (REQ-API-021, REQ-OPS-042,
 * ADR-0135).
 *
 * <p>The vhost admits exactly the frozen operations, the two anonymous reads and the retired
 * operations, each as one anchored regular expression on {@code "$request_method:$uri"} in one
 * nginx {@code map}; every other verb and path is refused with {@code 404}. The same model yields
 * the nightly probe's table and the requests the live-nginx test drives. {@code ./gradlew
 * :backend:generateEdgeAdmission} writes the generated files.
 */
