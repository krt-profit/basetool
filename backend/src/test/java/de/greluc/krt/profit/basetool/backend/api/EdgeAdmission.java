  /** The shape of a uuid placeholder. */
  private static final Shape UUID_SHAPE = new Shape(UUID_REGEX, List.of(SAMPLE_UUID));

  /** The shape of a boolean placeholder. */
  private static final Shape BOOLEAN_SHAPE = new Shape("(true|false)", List.of("true", "false"));

