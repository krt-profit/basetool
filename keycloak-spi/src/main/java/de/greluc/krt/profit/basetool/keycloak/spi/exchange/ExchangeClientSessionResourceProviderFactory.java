package de.greluc.krt.profit.basetool.keycloak.spi.exchange;

import org.jetbrains.annotations.NotNull;
import org.keycloak.Config;
import org.keycloak.models.KeycloakSession;
import org.keycloak.models.KeycloakSessionFactory;
import org.keycloak.services.resources.admin.ext.AdminRealmResourceProvider;
import org.keycloak.services.resources.admin.ext.AdminRealmResourceProviderFactory;

/**
 * Registers the {@code basetool-exchange} admin extension, the path segment after {@code
 * /admin/realms/{realm}/}.
 */
public class ExchangeClientSessionResourceProviderFactory
    implements AdminRealmResourceProviderFactory {

  /** The extension's path segment and provider id. */
  public static final String PROVIDER_ID = "basetool-exchange";

  @Override
  public @NotNull AdminRealmResourceProvider create(KeycloakSession session) {
    return new ExchangeClientSessionResourceProvider();
  }

  @Override
  public void init(Config.Scope config) {}

  @Override
  public void postInit(KeycloakSessionFactory factory) {}

  @Override
  public void close() {}

  @Override
  public @NotNull String getId() {
    return PROVIDER_ID;
  }
}
