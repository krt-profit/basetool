package de.greluc.krt.profit.basetool.keycloak.spi.exchange;

import org.jetbrains.annotations.NotNull;
import org.keycloak.models.KeycloakSession;
import org.keycloak.models.RealmModel;
import org.keycloak.services.resources.admin.AdminEventBuilder;
import org.keycloak.services.resources.admin.ext.AdminRealmResourceProvider;
import org.keycloak.services.resources.admin.fgap.AdminPermissionEvaluator;

/** Mounts {@link ExchangeClientSessionResource} under the realm's admin API. */
public class ExchangeClientSessionResourceProvider implements AdminRealmResourceProvider {

  @Override
  public @NotNull Object getResource(
      KeycloakSession session,
      RealmModel realm,
      AdminPermissionEvaluator auth,
      AdminEventBuilder adminEvent) {
    return new ExchangeClientSessionResource(session, realm, auth, adminEvent);
  }

  @Override
  public void close() {}
}
